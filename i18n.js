(() => {
  const root = document.documentElement;
  let lang;
  try { lang = localStorage.getItem("lang"); } catch {}
  if (!T[lang]) lang = (navigator.languages?.[0] || navigator.language || "en").toLowerCase().startsWith("es") ? "es" : "en";
  const forced = window.FORCE_LANG; // monolingual pages (pappos.html, yellowsub.html)
  if (T[forced]) lang = forced;

  window.t = (key) => T[lang][key] ?? key;
  window.lang = () => lang;

  function apply(l) {
    lang = l;
    root.lang = l;
    document.querySelectorAll("[data-i18n]").forEach((el) => { el.textContent = t(el.dataset.i18n); });
    document.querySelectorAll("[data-i18n-label]").forEach((el) => el.setAttribute("aria-label", t(el.dataset.i18nLabel)));
    document.getElementById("metaDesc").content = t("meta.desc");
    const btn = document.getElementById("langToggle");
    if (btn) {
      btn.textContent = l === "en" ? "ES" : "EN";
      btn.setAttribute("aria-label", t("a11y.lang"));
    }
    dispatchEvent(new Event("langchange"));
  }

  document.addEventListener("DOMContentLoaded", () => {
    document.getElementById("langToggle")?.addEventListener("click", () => {
      apply(lang === "en" ? "es" : "en");
      if (!forced) try { localStorage.setItem("lang", lang); } catch {} // persist only an explicit choice; first visit follows the browser
    });
    apply(lang);
  });
})();
